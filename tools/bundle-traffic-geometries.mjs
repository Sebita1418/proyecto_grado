import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const geometryInputs = [
  { code: '68001', name: 'Bucaramanga', asset: 'bucaramanga-mgn2024.geojson' },
  { code: '68307', name: 'Girón', asset: 'giron-mgn2024.geojson' },
  { code: '68276', name: 'Floridablanca', asset: 'floridablanca-mgn2024.geojson' },
];
const repository = new URL('../', import.meta.url);
export const outputUrl = new URL('supabase/functions/traffic-flow/geometries.generated.ts', repository);
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');

export async function generateModule() {
  const geometries = [], sources = [];
  for (const input of geometryInputs) {
    const asset = `assets/geo/${input.asset}`;
    const bytes = await readFile(new URL(asset, repository));
    const collection = JSON.parse(bytes.toString('utf8'));
    if (collection.type !== 'FeatureCollection' || !collection.features?.length) {
      throw new Error(`Invalid original collection: ${asset}`);
    }
    const originalGeometries = collection.features.map(feature => feature.geometry);
    for (const geometry of originalGeometries) {
      if (!['Polygon', 'MultiPolygon'].includes(geometry?.type) || !Array.isArray(geometry.coordinates)) {
        throw new Error(`Unsupported original geometry: ${asset}`);
      }
    }
    sources.push({ ...input, asset, originalSha256: sha256(bytes),
      featureCount: originalGeometries.length,
      geometriesSha256: sha256(JSON.stringify(originalGeometries)) });
    // Same JSON.parse numeric representation as the former Deno JSON loader.
    // Preserve every coordinate, ring, hole, polygon and feature in input order.
    geometries.push(...originalGeometries);
  }
  return '// Generated by node tools/bundle-traffic-geometries.mjs; do not edit.\n' +
    '// Original DANE attribution/licensing: assets/geo/README.md. No simplification or reprojection.\n' +
    `export const geometrySources = ${JSON.stringify(sources)};\n` +
    `export const geometries = ${JSON.stringify(geometries)};\n`;
}

async function main() {
  const generated = await generateModule();
  if (process.argv.includes('--check')) {
    if (await readFile(outputUrl, 'utf8') !== generated) {
      throw new Error('Generated module differs; run node tools/bundle-traffic-geometries.mjs');
    }
    console.log('PASS: bundled geometries match original assets exactly');
  } else {
    await writeFile(outputUrl, generated, 'utf8');
    console.log(`Generated ${fileURLToPath(outputUrl)} (${Buffer.byteLength(generated)} bytes)`);
  }
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) await main();
